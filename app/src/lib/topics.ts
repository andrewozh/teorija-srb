export function getTopicsForSection(sectionId: string): Topic[] | null {
	const st = SECTION_TOPICS.find(s => s.sectionId === sectionId);
	return st ? st.topics : null;
}

export function topicName(topic: Topic, lang: Lang): string {
	return topic.name[lang] || topic.name.sr;
}

export function topicHint(topic: Topic, lang: Lang): string {
	return topic.hint[lang] || topic.hint.sr;
}
